# export the graph node and edges to GraphML format
# Must be readable by Visone
def create_graphml_file(network_with_affiliation_attributes :nx.Graph,
                        out_file_name: Path,
                        verbose=True,
                        weighted: bool = False,
                        metadata: Optional[Dict[str, str]] = None) -> None:
    """Write a network of individuals to GraphML: numeric node IDs with e-mail, color and
    affiliation attributes. With weighted=True, each edge also gets its 'weight' attribute.
    metadata (see scraplog.metadata) is written as graph-level attributes."""
    # iterator for nAf  

    # Accept both string and Path
    if isinstance(out_file_name, str):
        out_file_name = Path(out_file_name)
    elif not isinstance(out_file_name, Path):
        raise TypeError(f"{out_file_name} must be a string or Path object")

    if verbose:
            console.print(f"Exporting graph to file (.graphml): {out_file_name=}")
    
    # verify arguments data
    ## verify graph/network 

    if network_with_affiliation_attributes is None:
        print_fatal_error("The network to export is None")
        print_fatal_error("The input did not led to the creation of a valid network ")
        console.print(f"Attempting to export {network_with_affiliation_attributes=}")
        exit(1)
    
    if network_with_affiliation_attributes.order() < 2:
        print_fatal_error("Network have less than two nodes !")
        exit(1)

    if network_with_affiliation_attributes.size() < 1:
        print_fatal_error("Network have less than one edge !!")
        exit(1)

        
    ## verify affiliations
    (valid_graph_with_affiliations, mising_nodes) = validate_all_graph_nodes_have_affiliation_attributes(network_with_affiliation_attributes)

    console.print(f"{valid_graph_with_affiliations=},{ mising_nodes=}")

    if not valid_graph_with_affiliations :
        print_fatal_error("Not all nodes have affiliation attributes !")
        print_info(f"Attempting to export {network_with_affiliation_attributes=} failed" )
        raise (AffiliationValidationError(
            f"{len(network_with_affiliation_attributes)}/{network_with_affiliation_attributes.number_of_nodes()} node(s) missing 'affiliation' "
            f"— cannot export to GraphML. First 5: {mising_nodes[:5]}"
        ))

    "verify every node as affiliation data"
    for node, data in network_with_affiliation_attributes.nodes(data=True):
        #console.print(f"{node}: {data['affiliation']}")

        if None == data['affiliation']:
            break

        if len(data['affiliation']) == 0:
            print_fatal_error("invalid affiliation attribute")
            console.print(f'{node=}')
            console.print(f'{data['affiliation']}')
            exit(1)
        if 'affiliation' not in data.keys():
            print_fatal_error("affiliation attribute is missing")
            console.print(f'{node=}')
            console.print(f'{data['affiliation']}')
            exit(1)


        if isinstance(out_file_name, str):
            out_file_name = Path(out_file_name)  # Convert string to Path
        elif isinstance(out_file_name, Path):
            pass  # Already a Path, do nothing
        else:
            # Only error on truly invalid types
            print_fatal_error("Invalid output filename",
                              f"Must be Path or string, got {type(out_file_name).__name__}: {repr(out_file_name)}")
        
    if len(out_file_name.name) < 5 :
        print_fatal_error("\tERROR outfilename must be a long string. More than 5 characters !")
        sys.exit(1)
    if out_file_name.suffix.lower() != ".graphml":
        print_fatal_error("\tERROR outfilename must finish with .graphml extension")
        sys.exit(1)

    # open the export file 


    print_info(f"Writing graphml file  (for VISONE SNA tool or other ) {out_file_name= }")

    gfile= open(out_file_name, 'w')

    
    # open XML headers 
    gfile.writelines(export_graphml_format.graphml_header)
    
    # Add grapth atributes 

    gfile.writelines(export_graphml_format.setNodeAntributeKey(0,"e-mail","string"))
    gfile.writelines(export_graphml_format.setNodeAntributeKey(1,"color","string"))
    gfile.writelines(export_graphml_format.setNodeAntributeKey(2,"affiliation","string"))
    if weighted:
        gfile.writelines(export_graphml_format.setEdgeAttributeKey(3,"weight","long"))
    if metadata:
        gfile.write(graphml_metadata_keys(metadata))


    # Open grapth 
    gfile.writelines(export_graphml_format.graph_opener)
    if metadata:
        gfile.write(graphml_metadata_data(metadata))
    
    # store the nodes id for each email/contributor
    tmpNodeId = {} 

    "for now all colors are turquoise"

    print ()
    print ("\t\tWriting nodes in graphML file")
    node_id = 0
    # Sorted by email so that the same input always gives byte-identical output
    # (graph iteration order depends on set ordering, which varies between runs)
    for node in sorted(network_with_affiliation_attributes.nodes()):
        data = network_with_affiliation_attributes.nodes[node]
        email=node
        afl= data['affiliation']
        #print(exportGraphml.addNode(nAf,[(0,email),(1,"turquoise"),(2,afl)]))
        if afl == None :
            gfile.writelines(export_graphml_format.addNode(node_id, [(0, email), (1, "turquoise"), (2, "unknown")]))
            print_warning(f"node = {email=} does not have a known affiliation attribute")
        else:
            gfile.writelines(export_graphml_format.addNode(node_id,[(0,email),(1,"turquoise"),(2,afl)]))
        # Give a each node and numeric id atribute data as well 
        network_with_affiliation_attributes.nodes[node]['id']= node_id
        node_id+=1


    print ()
    print ("\t\tWriting edges in graphML file")
    
    # Undirected edges: write each as (smaller id, larger id), sorted, for deterministic output
    def edge_ids(edge):
        ids = (network_with_affiliation_attributes.nodes[edge[0]]['id'],
               network_with_affiliation_attributes.nodes[edge[1]]['id'])
        return min(ids), max(ids)

    nTup=0
    for edge in sorted(network_with_affiliation_attributes.edges(), key=edge_ids):
        nodeIdFrom, nodeIdTo = edge_ids(edge)
        #print("edge=",edge)
        #print("edge via id=",nodeIdFrom,nodeIdTo)
        
        
        #print(exportGraphml.addEdge("e"+str(nTup),nodeIdFrom,nodeIdTo))
        if weighted:
            weight = network_with_affiliation_attributes.edges[edge]['weight']
            gfile.writelines(export_graphml_format.addEdgeWithAttributes("e"+str(nTup),nodeIdFrom,nodeIdTo,[(3, weight)]))
        else:
            gfile.writelines(export_graphml_format.addEdge("e"+str(nTup),nodeIdFrom,nodeIdTo))
        nTup+=1

        if edge[0] == edge[1]:
            print ("\t ERROR arc between the same mail/node/developer")
            print(("\t edge=["+str(edge)+"]"))
            sys.exit(1)            
    
    # Close grapth
    gfile.writelines(export_graphml_format.graph_closer)

    # close XML document 
    gfile.writelines(export_graphml_format.graphml_closer)

    # close the export file 
    gfile.close()



def temporal_graphml_text(temporal_network: nx.MultiGraph, metadata: Optional[Dict[str, str]] = None) -> str:
    """GraphML for a temporal network of individuals, laid out like create_graphml_file's output.

    Numeric node IDs (0, 1, ... in e-mail order) with e-mail, color and affiliation attributes,
    and one edge per time-stamped co-edit with a 'time' attribute (ISO 8601, as in the log).
    Edge IDs are e0, e1, ... in (source, target, time) order, time by instant. E-mails are not
    used as IDs because GraphML IDs cannot contain '@', and every edge has its own ID.
    temporal_network: a plain networkx MultiGraph (see temporal_as_multigraph) whose nodes have
    their affiliation attribute set (see enrich_graph_with_affiliation).
    """
    node_id = {email: i for i, email in enumerate(sorted(temporal_network.nodes()))}

    parts = [export_graphml_format.graphml_header,
             export_graphml_format.setNodeAntributeKey(0, "e-mail", "string"),
             export_graphml_format.setNodeAntributeKey(1, "color", "string"),
             export_graphml_format.setNodeAntributeKey(2, "affiliation", "string"),
             export_graphml_format.setEdgeAttributeKey(3, "time", "string")]
    if metadata:
        parts.append(graphml_metadata_keys(metadata))
    parts.append(export_graphml_format.graph_opener)
    if metadata:
        parts.append(graphml_metadata_data(metadata))

    for email, i in node_id.items():
        affiliation = temporal_network.nodes[email].get('affiliation') or "unknown"
        parts.append(export_graphml_format.addNode(i, [(0, email), (1, "turquoise"), (2, affiliation)]))

    def edge_order(edge):
        source, target, time = edge
        return source, target, datetime.fromisoformat(time), time

    edges = sorted(((min(node_id[u], node_id[v]), max(node_id[u], node_id[v]), str(time))
                    for u, v, time in temporal_network.edges(data='time')), key=edge_order)
    for n, (source, target, time) in enumerate(edges):
        parts.append(export_graphml_format.addEdgeWithAttributes("e" + str(n), source, target, [(3, time)]))

    parts.append(export_graphml_format.graph_closer)
    parts.append(export_graphml_format.graphml_closer)
    return "".join(parts)


def temporal_as_multigraph(temporal_network) -> nx.MultiGraph:
    """The co-edits of a networkx-temporal graph as a plain networkx MultiGraph (one edge per co-edit)."""
    multigraph = nx.MultiGraph()
    multigraph.add_edges_from(temporal_network.temporal_edges(data=True))
    return multigraph


def write_temporal_graphml_zip(temporal_network: nx.MultiGraph, zip_file: Path,
                               metadata: Optional[Dict[str, str]] = None) -> None:
    """Write temporal_graphml_text to a zip archive holding <zip name without .zip>, e.g.
    t.temporal.graphml.zip holds t.temporal.graphml (a name without .zip is used as it is). The
    entry has a fixed date, so the same network gives the same bytes."""
    name = Path(zip_file).name
    if name.lower().endswith(".zip"):
        name = name[:-len(".zip")]
    entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
    entry.external_attr = 0o600 << 16
    with zipfile.ZipFile(zip_file, "w") as archive:
        archive.writestr(entry, temporal_graphml_text(temporal_network, metadata).encode("utf-8"))
